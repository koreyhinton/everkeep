#!/bin/bash

# Prints the drag-select tests as one Rust file (test.sh writes it to
# tests/drag_select.rs). Written test-first: the two snippets they inline,
# src/update-drag-select.sh and src/draw-selection.sh, don't exist yet, so
# generation leaves them out and every test fails until they're added.
#
# The tests play a left-button drag over three frames (press, move, release)
# through stubbed mouse functions, run update-drag-select.sh each frame, then
# run draw-selection.sh once. As in draw-unit.test.sh, local fns shadow
# macroquad's glob import: the mouse stubs read a scripted state, and the
# draw_rectangle_lines stub records each rectangle instead of drawing it.
#
# What the snippets need to provide (the interface these tests fix):
#   update-drag-select.sh  binds DragStart (Option<Vec2>), Unit, Houses.
#       Left press starts a drag; release selects what the drag rectangle
#       encloses. Units win: if the drag holds a unit, no building is selected.
#   draw-selection.sh      binds Unit, Houses. Draws one draw_rectangle_lines
#       per selected unit or house, "nearby": it encloses the hitbox (pos +
#       hitbox) with no edge more than NEAR pixels outside it.

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}drag_DragStart=drag_start
export ${v}drag_Unit=unit
export ${v}drag_Houses=houses
export ${v}sel_Unit=unit
export ${v}sel_Houses=houses

cat << EOF
// Code generated by tests/drag-select.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]

use macroquad::prelude::*;
use std::cell::RefCell;

// a selection rectangle may sit at most this far outside the hitbox
const NEAR: f32 = 16.0;

// same footprints as the game: relative to the unit's feet and the
// house's bottom-center
const UNIT_HITBOX: Rect = Rect::new(-24.0, -64.0, 48.0, 64.0);
const HOUSE_HITBOX: Rect = Rect::new(-56.0, -72.0, 112.0, 72.0);

struct Unit {
    pos: Vec2,
    hitbox: Rect,
    selected: bool,
}

struct Building {
    pos: Vec2,
    hitbox: Rect,
    selected: bool,
}

// the mouse as the stubs report it for the current frame
#[derive(Clone, Copy, Default)]
struct Mouse {
    pos: (f32, f32),
    pressed: bool,
    down: bool,
    released: bool,
}

thread_local! {
    static MOUSE: RefCell<Mouse> = RefCell::new(Mouse::default());
    static RECTS: RefCell<Vec<Rect>> = RefCell::new(Vec::new());
}

fn mouse_position() -> (f32, f32) {
    MOUSE.with(|mouse| mouse.borrow().pos)
}

fn is_mouse_button_pressed(button: MouseButton) -> bool {
    button == MouseButton::Left && MOUSE.with(|mouse| mouse.borrow().pressed)
}

fn is_mouse_button_down(button: MouseButton) -> bool {
    button == MouseButton::Left && MOUSE.with(|mouse| mouse.borrow().down)
}

fn is_mouse_button_released(button: MouseButton) -> bool {
    button == MouseButton::Left && MOUSE.with(|mouse| mouse.borrow().released)
}

fn set_mouse(mouse: Mouse) {
    MOUSE.with(|current| *current.borrow_mut() = mouse);
}

fn draw_rectangle_lines(x: f32, y: f32, w: f32, h: f32, _thickness: f32, _color: Color) {
    RECTS.with(|rects| rects.borrow_mut().push(Rect::new(x, y, w, h)));
}

fn drawn_rects() -> Vec<Rect> {
    RECTS.with(|rects| rects.borrow_mut().drain(..).collect())
}

fn world_hitbox(pos: Vec2, hitbox: Rect) -> Rect {
    Rect::new(pos.x + hitbox.x, pos.y + hitbox.y, hitbox.w, hitbox.h)
}

fn assert_nearby(drawn: Rect, pos: Vec2, hitbox: Rect) {
    let target = world_hitbox(pos, hitbox);
    let encloses = drawn.left() <= target.left()
        && drawn.top() <= target.top()
        && drawn.right() >= target.right()
        && drawn.bottom() >= target.bottom();
    let close = target.left() - drawn.left() <= NEAR
        && target.top() - drawn.top() <= NEAR
        && drawn.right() - target.right() <= NEAR
        && drawn.bottom() - target.bottom() <= NEAR;
    assert!(
        encloses && close,
        "selection {drawn:?} is not a nearby rectangle around {target:?}"
    );
}

fn new_unit(pos: Vec2) -> Unit {
    Unit { pos, hitbox: UNIT_HITBOX, selected: false }
}

fn new_house(pos: Vec2) -> Building {
    Building { pos, hitbox: HOUSE_HITBOX, selected: false }
}

// the three mouse states of a left-button drag from one corner to another
fn press_at(pos: (f32, f32)) -> Mouse {
    Mouse { pos, pressed: true, down: true, released: false }
}

fn drag_to(pos: (f32, f32)) -> Mouse {
    Mouse { pos, pressed: false, down: true, released: false }
}

fn release_at(pos: (f32, f32)) -> Mouse {
    Mouse { pos, pressed: false, down: false, released: true }
}

#[test]
fn drag_around_a_unit_draws_a_nearby_rectangle() {
    let mut drag_start: Option<Vec2> = None;
    let mut unit = new_unit(vec2(300.0, 300.0));
    let mut houses: Vec<Building> = vec![];

    // unit hitbox spans (276, 236) to (324, 300)
    for mouse in [press_at((250.0, 210.0)), drag_to((350.0, 330.0)), release_at((350.0, 330.0))] {
        set_mouse(mouse);
        ` ./update-drag-select.sh ${v}drag_ `
    }
    ` ./draw-selection.sh ${v}sel_ `

    let rects = drawn_rects();
    assert_eq!(rects.len(), 1, "expected one selection rectangle, drew {rects:?}");
    assert_nearby(rects[0], unit.pos, unit.hitbox);
}

#[test]
fn drag_around_a_building_selects_it_with_a_nearby_rectangle() {
    let mut drag_start: Option<Vec2> = None;
    // the unit stays out of the drag
    let mut unit = new_unit(vec2(600.0, 400.0));
    let mut houses = vec![new_house(vec2(200.0, 200.0))];

    // house hitbox spans (144, 128) to (256, 200)
    for mouse in [press_at((120.0, 100.0)), drag_to((280.0, 230.0)), release_at((280.0, 230.0))] {
        set_mouse(mouse);
        ` ./update-drag-select.sh ${v}drag_ `
    }
    ` ./draw-selection.sh ${v}sel_ `

    let rects = drawn_rects();
    assert_eq!(rects.len(), 1, "expected one selection rectangle, drew {rects:?}");
    assert_nearby(rects[0], houses[0].pos, houses[0].hitbox);
}

#[test]
fn drag_around_a_building_and_a_unit_selects_only_the_unit() {
    let mut drag_start: Option<Vec2> = None;
    let mut unit = new_unit(vec2(300.0, 300.0));
    let mut houses = vec![new_house(vec2(200.0, 200.0))];

    // encloses the house (144, 128)-(256, 200) and the unit (276, 236)-(324, 300)
    for mouse in [press_at((120.0, 100.0)), drag_to((350.0, 330.0)), release_at((350.0, 330.0))] {
        set_mouse(mouse);
        ` ./update-drag-select.sh ${v}drag_ `
    }
    ` ./draw-selection.sh ${v}sel_ `

    let rects = drawn_rects();
    assert_eq!(rects.len(), 1, "expected only the unit's selection rectangle, drew {rects:?}");
    assert_nearby(rects[0], unit.pos, unit.hitbox);
}
EOF
