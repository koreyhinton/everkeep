#!/bin/bash

# Prints the draw-unit tests as one Rust file (test.sh writes it to
# tests/draw_unit.rs). It plays main.sh's per-unit animation step (orc's
# animate-sprite, then update-unit-frame.sh) and draws with draw-world.sh.
#
# draw_texture_ex is stubbed here: a local fn shadows macroquad's glob
# import, so the snippet calls the stub, which records the draw instead of
# needing a window. Textures are Strings, so a test can see which was drawn.

: "${ORC_ANIMATE:?set ORC_ANIMATE (see test.sh)}"
: "${NSMAP:?set NSMAP (see test.sh)}"
: "${ORC_ANIMATE_VERSION:?set ORC_ANIMATE_VERSION (see orc-env.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}anim_AnimatedSprite=pawn_sprite
export ${v}frame_Unit=units[0]
export ${v}frame_Sprite=pawn_sprite
export ${v}world_Units=units
export ${v}world_Buildings=buildings
export ${v}world_View=view
export ${v}world_HallTextures=hall_textures
export ${v}world_PawnTextures=pawn_textures
# no map: these tests draw units and buildings, not trees
export ${v}world_Tiles=NO_TILES
export ${v}world_TreeTextures='no_trees()'
# no fog: everything is in sight, including the other player's units
export ${v}world_Me=0
export ${v}world_Light='full_light()'

cat << EOF
// Code generated by tests/draw-unit.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the game's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;
use std::cell::RefCell;

EOF

# the game's constants and types
./models.sh
${ORC_PATHFINDING}/models.sh "${ORC_PATHFINDING_VERSION}" || exit 1

# between heredocs, not in backticks, so a version mismatch stops generation
${ORC_ANIMATE}/models.sh "${ORC_ANIMATE_VERSION}" || exit 1

cat << EOF

// what one draw_texture_ex call would have drawn
#[derive(Debug, PartialEq)]
struct Drawn {
    texture: String,
    x: f32,
    y: f32,
    source: Option<Rect>,
    flip_x: bool,
}

thread_local! {
    static DRAWN: RefCell<Vec<Drawn>> = RefCell::new(Vec::new());
}

const NO_TILES: &[&str] = &[];

fn full_light() -> Vec<f32> {
    vec![1.0; FOG_W * FOG_H]
}

fn no_trees() -> [String; 4] {
    ["tree1", "tree2", "tree3", "tree4"].map(String::from)
}

// draw-world.sh sways trees by the clock
fn get_time() -> f64 {
    0.0
}

fn draw_texture_ex(texture: &String, x: f32, y: f32, _color: Color, params: DrawTextureParams) {
    DRAWN.with(|drawn| {
        drawn.borrow_mut().push(Drawn {
            texture: texture.clone(),
            x,
            y,
            source: params.source,
            flip_x: params.flip_x,
        })
    });
}

fn draw_texture(_texture: &String, _x: f32, _y: f32, _color: Color) {}

fn draw_rectangle_lines(_x: f32, _y: f32, _w: f32, _h: f32, _thickness: f32, _color: Color) {}

fn drawn() -> Vec<Drawn> {
    DRAWN.with(|drawn| drawn.borrow_mut().drain(..).collect())
}

fn idle() -> Animation {
    Animation { id: "idle".to_string(), row: 0, frames: 8, fps: 10.0 }
}

fn run() -> Animation {
    Animation { id: "run".to_string(), row: 0, frames: 6, fps: 10.0 }
}

fn new_sprite(animation: &Animation) -> AnimatedSprite<'_> {
    AnimatedSprite {
        w: 192.0,
        h: 192.0,
        frame: 0,
        frame_time: 0.0,
        animation,
        last_animation_id: String::new(),
        paint_frame: None,
    }
}

fn new_unit(owner: usize, pos: Vec2, running: bool, flip: bool) -> Unit {
    Unit {
        id: 0,
        owner,
        pos,
        target: pos,
        dir: Vec2::ZERO,
        speed: UNIT_SPEED,
        hitbox: UNIT_HITBOX,
        selected: false,
        flip,
        running,
        frame: Rect::new(0.0, 0.0, 0.0, 0.0),
        path: vec![],
        repath: false,
    }
}

fn textures() -> ([String; 2], [[String; 2]; 2]) {
    (
        ["hall".to_string(), "red_hall".to_string()],
        [
            ["idle".to_string(), "run".to_string()],
            ["red_idle".to_string(), "red_run".to_string()],
        ],
    )
}

// A unit whose sprite hasn't animated yet (such as one trained this frame)
// has no frame to draw, and must be skipped rather than drawn empty.
#[test]
fn draw_before_the_first_update_draws_nothing() {
    let (hall_textures, pawn_textures) = textures();
    let units = vec![new_unit(0, vec2(300.0, 200.0), false, false)];
    let buildings: Vec<Building> = vec![];
    let view = Vec2::ZERO;

    ` ./draw-world.sh ${v}world_ `

    assert_eq!(drawn(), vec![]);
}

#[test]
fn draw_after_an_update_uses_the_paint_frame() {
    let (hall_textures, pawn_textures) = textures();
    let idle_animation = idle();
    let mut pawn_sprite = new_sprite(&idle_animation);
    let mut units = vec![new_unit(0, vec2(300.0, 200.0), false, false)];
    let buildings: Vec<Building> = vec![];
    let view = Vec2::ZERO;

    ` ${ORC_ANIMATE}/snippets/macroquad/animate-sprite.sh ${v}anim_ `
    pawn_sprite.frame_time += 0.2;
    ` ${ORC_ANIMATE}/snippets/macroquad/animate-sprite.sh ${v}anim_ `
    ` ./update-unit-frame.sh ${v}frame_ `
    ` ./draw-world.sh ${v}world_ `

    // feet at (96, 128) in the frame, frame 1 of the idle row
    assert_eq!(drawn(), vec![Drawn {
        texture: "idle".to_string(),
        x: 204.0,
        y: 72.0,
        source: Some(Rect::new(192.0, 0.0, 192.0, 192.0)),
        flip_x: false,
    }]);
}

#[test]
fn draw_while_running_uses_the_run_texture_and_flip() {
    let (hall_textures, pawn_textures) = textures();
    let run_animation = run();
    let mut pawn_sprite = new_sprite(&run_animation);
    let mut units = vec![new_unit(0, vec2(300.0, 200.0), true, true)];
    let buildings: Vec<Building> = vec![];
    let view = Vec2::ZERO;

    ` ${ORC_ANIMATE}/snippets/macroquad/animate-sprite.sh ${v}anim_ `
    ` ./update-unit-frame.sh ${v}frame_ `
    ` ./draw-world.sh ${v}world_ `

    assert_eq!(drawn(), vec![Drawn {
        texture: "run".to_string(),
        x: 204.0,
        y: 72.0,
        source: Some(Rect::new(0.0, 0.0, 192.0, 192.0)),
        flip_x: true,
    }]);
}

#[test]
fn the_other_players_unit_uses_their_textures_and_the_view_offset() {
    let (hall_textures, pawn_textures) = textures();
    let idle_animation = idle();
    let mut pawn_sprite = new_sprite(&idle_animation);
    let mut units = vec![new_unit(1, vec2(1300.0, 900.0), false, false)];
    let buildings: Vec<Building> = vec![];
    let view = vec2(1000.0, 700.0);

    ` ${ORC_ANIMATE}/snippets/macroquad/animate-sprite.sh ${v}anim_ `
    ` ./update-unit-frame.sh ${v}frame_ `
    ` ./draw-world.sh ${v}world_ `

    assert_eq!(drawn(), vec![Drawn {
        texture: "red_idle".to_string(),
        x: 204.0,
        y: 72.0,
        source: Some(Rect::new(0.0, 0.0, 192.0, 192.0)),
        flip_x: false,
    }]);
}
EOF
