    let world = new_world(2, 42);
    let before = checksum_of(&world);
    let mut found = new_world(2, 42);
    found.objectives[1] = OBJ_FIND_RIVAL_HALL;
    assert_ne!(checksum_of(&found), before, "objectives aren't in the checksum");
}

