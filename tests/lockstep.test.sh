#!/bin/bash

# Prints the lockstep tests as one Rust file (test.sh writes it to
# tests/lockstep.rs).
#
# Online, every player runs the sim on their own machine. They stay in step
# only if the sim is deterministic: the same seed and the same commands on
# the same turns must give the same world on every machine. These tests run
# the game's sim steps (world-reset, apply-commands, update-units,
# world-checksum) the way main.sh's tick loop does, and check the rules that
# keep a command from the network from cheating or crashing the sim. They
# also check the messages exchanged with sharecmd's lockstep server
# (net-turn-msg.sh out, net-recv.sh in).

: "${NSMAP:?set NSMAP (see test.sh)}"

cd "$(dirname "${BASH_SOURCE[0]}")/../src" || exit 1

v=mn_
# maps
export ${v}reset_World=world
export ${v}reset_Players=players
export ${v}reset_Seed=seed
export ${v}apply_Commands=turn_cmds[player]
export ${v}apply_Player=player
export ${v}apply_Units=world.units
export ${v}apply_Buildings=world.buildings
export ${v}apply_Gold=world.gold
export ${v}apply_NextId=world.next_id
export ${v}units_Units=world.units
export ${v}units_DeltaT=TICK_SECS
export ${v}sum_World=world
export ${v}sum_Checksum=checksum
export ${v}msg_Commands=commands
export ${v}msg_NextSend=next_send
export ${v}msg_TurnMsg=turn_msg
export ${v}recv_Text=text
export ${v}recv_Confirmed=confirmed
export ${v}recv_Started=started
export ${v}recv_EndReason=end_reason

cat << EOF
// Code generated by tests/lockstep.test.sh. DO NOT EDIT.
#![allow(non_snake_case)]
// the game's models cover more than these tests use
#![allow(dead_code)]

use macroquad::prelude::*;
use std::collections::BTreeMap;

EOF

# the game's constants and types
./models.sh

cat << EOF

fn screen_width() -> f32 {
    800.0
}

fn screen_height() -> f32 {
    600.0
}

fn new_world(players: u32, seed: u64) -> World {
    let mut world = World {
        units: vec![],
        buildings: vec![],
        gold: [START_GOLD; 2],
        me: 0,
        placing: None,
        drag_start: None,
        view: Vec2::ZERO,
        next_id: 0,
        outbox: vec![],
    };
    ` ./world-reset.sh ${v}reset_ `
    world
}

// main.sh's tick loop, with every turn's commands already confirmed:
// apply both players' commands at each turn, then step the units each tick
fn run_turns(world: &mut World, mut confirmed: BTreeMap<u32, [Vec<Command>; 2]>, turns: u32) {
    for tick in 0..turns * TICKS_PER_TURN {
        if tick % TICKS_PER_TURN == 0 {
            let turn_cmds = confirmed.remove(&(tick / TICKS_PER_TURN)).unwrap_or_default();
            for player in 0..2usize {
                ` ./apply-commands.sh ${v}apply_ `
            }
        }
        ` ./update-units.sh ${v}units_ `
    }
}

fn checksum_of(world: &World) -> u32 {
    ` ./world-checksum.sh ${v}sum_ `
    checksum
}

// a short match: each player builds a hall, trains a pawn, and moves out
fn a_match(world: &World) -> BTreeMap<u32, [Vec<Command>; 2]> {
    let p0 = world.units.iter().find(|unit| unit.owner == 0).unwrap().pos;
    let p1 = world.units.iter().find(|unit| unit.owner == 1).unwrap().pos;
    let mut confirmed = BTreeMap::new();
    confirmed.insert(1, [
        vec![Command::PlaceHall { x: p0.x as i32 + 300, y: p0.y as i32 }],
        vec![Command::PlaceHall { x: p1.x as i32 - 300, y: p1.y as i32 }],
    ]);
    // ids: 0 and 1 are the starting pawns, 2 and 3 the halls, 4 and 5 the new pawns
    confirmed.insert(3, [vec![Command::TrainPawn { hall: 2 }], vec![Command::TrainPawn { hall: 3 }]]);
    confirmed.insert(5, [
        vec![Command::Move { units: vec![0, 4], x: 1600, y: 1200 }],
        vec![Command::Move { units: vec![1, 5], x: 1700, y: 1250 }],
    ]);
    confirmed
}

#[test]
fn the_same_seed_and_commands_give_the_same_world() {
    let mut a = new_world(2, 42);
    let mut b = new_world(2, 42);
    assert_eq!(checksum_of(&a), checksum_of(&b), "the same seed spawned different worlds");

    let (match_a, match_b) = (a_match(&a), a_match(&b));
    run_turns(&mut a, match_a, 120);
    run_turns(&mut b, match_b, 120);

    assert_eq!(a.buildings.len(), 2, "both halls should be built");
    assert_eq!(a.units.len(), 4, "both pawns should be trained");
    assert_eq!(a.gold, [START_GOLD - HALL_COST - PAWN_COST; 2]);
    assert_eq!(checksum_of(&a), checksum_of(&b), "the same commands gave different worlds");
}

#[test]
fn a_different_seed_spawns_a_different_world() {
    assert_ne!(checksum_of(&new_world(2, 1)), checksum_of(&new_world(2, 2)));
}

#[test]
fn a_player_cant_move_the_other_players_units() {
    let mut world = new_world(2, 7);
    let theirs = world.units.iter().find(|unit| unit.owner == 1).unwrap().pos;
    let mut confirmed = BTreeMap::new();
    // player 0 orders player 1's pawn (id 1)
    confirmed.insert(0, [vec![Command::Move { units: vec![1], x: 100, y: 100 }], vec![]]);
    run_turns(&mut world, confirmed, 10);
    assert_eq!(world.units[1].pos, theirs);
    assert_eq!(world.units[1].target, theirs);
}

#[test]
fn a_player_cant_train_at_the_other_players_hall() {
    let mut world = new_world(2, 7);
    let mut confirmed = BTreeMap::new();
    confirmed.insert(0, [vec![], vec![Command::PlaceHall { x: 2400, y: 1800 }]]);
    // player 0 trains at player 1's hall (id 2)
    confirmed.insert(1, [vec![Command::TrainPawn { hall: 2 }], vec![]]);
    run_turns(&mut world, confirmed, 3);
    assert_eq!(world.units.len(), 2);
    assert_eq!(world.gold[0], START_GOLD);
}

#[test]
fn nothing_is_built_or_trained_without_the_gold() {
    let mut world = new_world(1, 7);
    let mut confirmed = BTreeMap::new();
    // two halls use 400 of the 500 gold; the third can't be paid for
    confirmed.insert(0, [vec![
        Command::PlaceHall { x: 800, y: 800 },
        Command::PlaceHall { x: 1400, y: 800 },
        Command::PlaceHall { x: 2000, y: 800 },
    ], vec![]]);
    // 100 gold left: two pawns, then none
    confirmed.insert(1, [vec![
        Command::TrainPawn { hall: 1 },
        Command::TrainPawn { hall: 1 },
        Command::TrainPawn { hall: 1 },
    ], vec![]]);
    run_turns(&mut world, confirmed, 3);
    assert_eq!(world.buildings.len(), 2);
    assert_eq!(world.units.len(), 3);
    assert_eq!(world.gold[0], 0);
}

#[test]
fn halls_cant_overlap() {
    let mut world = new_world(1, 7);
    let mut confirmed = BTreeMap::new();
    confirmed.insert(0, [vec![
        Command::PlaceHall { x: 800, y: 800 },
        Command::PlaceHall { x: 850, y: 820 },
    ], vec![]]);
    run_turns(&mut world, confirmed, 1);
    assert_eq!(world.buildings.len(), 1);
    assert_eq!(world.gold[0], START_GOLD - HALL_COST);
}

#[test]
fn extreme_values_are_clamped_to_the_world() {
    let mut world = new_world(1, 7);
    let mut confirmed = BTreeMap::new();
    confirmed.insert(0, [vec![
        Command::Move { units: vec![0; 100_000], x: i32::MAX, y: i32::MIN },
        Command::PlaceHall { x: i32::MIN, y: i32::MAX },
    ], vec![]]);
    run_turns(&mut world, confirmed, 1);
    let unit = &world.units[0];
    assert!((0.0..=WORLD_W).contains(&unit.target.x) && (0.0..=WORLD_H).contains(&unit.target.y));
    let hall = &world.buildings[0];
    assert!((0.0..=WORLD_W).contains(&hall.pos.x) && (0.0..=WORLD_H).contains(&hall.pos.y));
}

#[test]
fn a_turn_message_is_what_the_server_expects() {
    let commands = vec![Command::Move { units: vec![0, 4], x: 740, y: 300 }];
    let mut next_send: u32 = 7;
    ` ./net-turn-msg.sh ${v}msg_ `
    assert_eq!(
        turn_msg,
        r#"{"type":"cmds","turn":7,"cmds":[{"op":"move","units":[0,4],"x":740,"y":300}]}"#
    );
    assert_eq!(next_send, 8);
}

#[test]
fn server_messages_start_confirm_turns_and_end() {
    let mut confirmed: BTreeMap<u32, [Vec<Command>; 2]> = BTreeMap::new();
    let mut started: Option<(usize, i64)> = None;
    let mut end_reason: Option<String> = None;
    let messages = [
        r#"{"type":"start","player":1,"seed":99}"#,
        // player 1 sent nothing (null); an unknown command is skipped
        r#"{"type":"turn","turn":3,"all":[[{"op":"place_hall","x":5,"y":6},{"op":"dance"}],null]}"#,
        r#"not json"#,
        r#"{"type":"end","reason":"player 0 left"}"#,
    ];
    for message in messages {
        let text = Some(message.to_string());
        ` ./net-recv.sh ${v}recv_ `
    }
    assert_eq!(started, Some((1, 99)));
    assert_eq!(confirmed.get(&3), Some(&[vec![Command::PlaceHall { x: 5, y: 6 }], vec![]]));
    assert_eq!(end_reason, Some("player 0 left".to_string()));
}
