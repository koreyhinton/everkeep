fn new_world(players: u32, seed: u64) -> World {
    let mut world = World {
        units: vec![],
        buildings: vec![],
        gold: [START_GOLD; 2],
        me: 0,
        placing: None,
        drag_start: None,
        view: Vec2::ZERO,
        next_id: 0,
        outbox: vec![],
